#!/usr/bin/env node
/**
 * Generates CSS mask icons for the Ext JS remote from @mui/icons-material, so
 * the legacy module renders exactly the same Material icons as the React
 * remotes (instead of Triton's Font Awesome 4 glyphs).
 *
 * Usage: node tools/scripts/generate-ext-icons.mjs
 * Output: apps/blotter/src/styles/icons.css (committed; re-run after edits).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** css name -> @mui/icons-material module */
const ICONS = {
  add: 'Add',
  refresh: 'Refresh',
  download: 'FileDownloadOutlined',
  approve: 'CheckCircleOutlined',
  reject: 'HighlightOffOutlined',
  route: 'SendOutlined',
  cancel: 'DoNotDisturbOnOutlined',
  search: 'SearchOutlined',
  close: 'CloseOutlined',
  info: 'InfoOutlined',
  warning: 'WarningAmberOutlined',
  error: 'ErrorOutlineOutlined',
  pass: 'CheckCircleOutlined',
  pending: 'HourglassTopOutlined',
  new: 'RadioButtonUncheckedOutlined',
  working: 'AutorenewOutlined',
  partial: 'DonutLargeOutlined',
  filled: 'TaskAltOutlined',
  cancelled: 'BlockOutlined',
  rejected: 'GppBadOutlined',
  copy: 'ContentCopyOutlined',
  portfolio: 'AccountBalanceWalletOutlined',
  trade: 'SwapHorizOutlined',
  receipt: 'ReceiptLongOutlined',
};

async function svgFor(module) {
  const source = await readFile(
    join(root, 'node_modules/@mui/icons-material', `${module}.js`),
    'utf8',
  );
  const paths = [...source.matchAll(/\bd: "([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`No path data found in ${module}`);
  const body = paths.map((d) => `<path d='${d}'/>`).join('');
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'>${body}</svg>`;
}

const rules = [];
for (const [name, module] of Object.entries(ICONS)) {
  const svg = await svgFor(module);
  rules.push(
    `.mrd-icon-${name} { --mrd-icon: url("data:image/svg+xml,${encodeURIComponent(svg)}"); }`,
  );
}

const css = `/* Generated by tools/scripts/generate-ext-icons.mjs from @mui/icons-material - do not edit. */
.mrd-icon {
  display: inline-block;
  flex: none;
  width: 18px;
  height: 18px;
  background-color: currentColor;
  -webkit-mask: var(--mrd-icon) center / contain no-repeat;
  mask: var(--mrd-icon) center / contain no-repeat;
}
${rules.join('\n')}
`;
const target = join(root, 'apps/blotter/src/styles/icons.css');
await writeFile(target, css);
console.log(`Wrote ${Object.keys(ICONS).length} icons -> ${target}`);
